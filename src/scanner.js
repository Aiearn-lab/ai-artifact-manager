/**
 * 递归收集文件（先只收集路径与基础元数据，不读内容）。
 */
async function collectFiles(root, options) {
  const opts = options || {};
  const maxDepth = Number.isInteger(opts.maxDepth) ? opts.maxDepth : 14;
  const maxFiles = Number.isInteger(opts.maxFiles) ? opts.maxFiles : 50000;
  const whitelist = Array.isArray(opts.whitelist) ? opts.whitelist : [];
  const includeExt = new Set((opts.includeExt || []).map((e) => String(e).toLowerCase()));
  const excludeExt = new Set((opts.excludeExt || []).map((e) => String(e).toLowerCase()));
  const onProgress = typeof opts.onProgress === 'function' ? opts.onProgress : null;
  const shouldStop = typeof opts.shouldStop === 'function' ? opts.shouldStop : null;

  const normalizedRoot = path.resolve(root);
  const wlPaths = whitelist
    .filter((w) => w && w.type === 'path' && w.value)
    .map((w) => path.resolve(w.value).toLowerCase());
  const wlExts = new Set(
    whitelist.filter((w) => w && w.type === 'ext' && w.value).map((w) => String(w.value).toLowerCase())
  );

  const files = [];
  const errors = [];
  let truncated = false;
  let cancelled = false;

  async function walk(dir, depth, inProject) {
    if (cancelled) return;
    if (shouldStop && shouldStop()) {
      cancelled = true;
      return;
    }
    if (files.length >= maxFiles) {
      truncated = true;
      return;
    }
    if (depth > maxDepth) return;

    let entries;
    try {
      entries = await fsp.readdir(dir, { withFileTypes: true });
    } catch (err) {
      errors.push({ path: dir, error: err.code || err.message });
      return;
    }

    // 项目标记：本目录有 package.json 或 .git，则本目录及子树的代码属于「项目内」。
    // 项目内代码只盘点不搬删——搬走一个被 import 的脚本，整个项目就断链报错。
    const projHere = inProject || entries.some(
      (e) => (e.isFile() && e.name === 'package.json') || (e.isDirectory() && e.name === '.git')
    );

    for (const entry of entries) {
      if (cancelled || (shouldStop && shouldStop())) {
        cancelled = true;
        return;
      }
      if (files.length >= maxFiles) {
        truncated = true;
        return;
      }
      const full = path.join(dir, entry.name);
      const lower = full.toLowerCase();

      if (entry.isSymbolicLink()) continue;

      if (entry.isDirectory()) {
        if (SKIP_DIRS_LOWER.has(entry.name.toLowerCase())) continue;
        if (wlPaths.some((p) => lower === p || lower.startsWith(p + path.sep))) continue;
        await walk(full, depth + 1, projHere);
        continue;
      }

      if (!entry.isFile()) continue;

      // 「卸载后请看.txt」是工具自己放进整理目录的说明，不是用户产出。
      // 让它进盘点，就有被判成「冗余可删」搬走的一天——说明书把自己说明没了。
      if (entry.name === OWN_NOTE) continue;

      const ext = path.extname(entry.name).toLowerCase();
      if (shouldSkipExt(ext)) continue;
      if (wlExts.has(ext)) continue;
      if (excludeExt.has(ext)) continue;
      if (includeExt.size > 0 && !includeExt.has(ext)) continue;
      if (!isTextExt(ext)) continue;

      let stat;
      try {
        stat = await fsp.stat(full);
      } catch (err) {
        errors.push({ path: full, error: err.code || err.message });
        continue;
      }

      files.push({
        path: full,
        name: entry.name,
        ext,
        size: stat.size,
        mtime: stat.mtimeMs,
        depth: depth + 1,
        inProject: !!projHere
      });

      if (onProgress && files.length % 200 === 0) onProgress(files.length);
    }
  }

  await walk(normalizedRoot, 0, false);
  if (onProgress) onProgress(files.length);
  return { files, errors, truncated, cancelled };
}

/**
 * 编码自适应（2026-11-06 P0）：UTF-8 / UTF-16(BOM) / GBK。
 * 记事本存的 GBK 中文以前按 UTF-8 硬解全是乱码，识别和查重一起失效。
 * 判据：先认 BOM；无 BOM 用严格 UTF-8 试解，解不动再试 GBK；都不行退回宽松 UTF-8。
 * TextDecoder 的 gbk 依赖 Node/Electron 自带的完整 ICU，缺失时优雅降级不崩。
 */
function decodeBuffer(buf) {
  if (buf.length >= 2 && buf[0] === 0xff && buf[1] === 0xfe) {
    try { return new TextDecoder('utf-16le').decode(buf.subarray(2)); } catch { /* 降级 */ }
  }
  if (buf.length >= 2 && buf[0] === 0xfe && buf[1] === 0xff) {
    try { return new TextDecoder('utf-16be').decode(buf.subarray(2)); } catch { /* 降级 */ }
  }
  let body = buf;
  if (buf.length >= 3 && buf[0] === 0xef && buf[1] === 0xbb && buf[2] === 0xbf) body = buf.subarray(3);
  try {
    return new TextDecoder('utf-8', { fatal: true }).decode(body);
  } catch {
    try { return new TextDecoder('gbk').decode(body); } catch { /* ICU 不全 */ }
    return body.toString('utf8');
  }
}

/**
 * 读取文本样本：最多读 maxBytes，返回 head + 字符数估算。
 */
async function readTextSample(filePath, size, maxBytes) {
  const limit = Math.min(size, maxBytes || 262144);
  let buf;
  try {
    const fd = await fsp.open(filePath, 'r');
    try {
      buf = Buffer.alloc(limit);
      const { bytesRead } = await fd.read(buf, 0, limit, 0);
      buf = buf.subarray(0, bytesRead);
    } finally {
      await fd.close();
    }
  } catch (err) {
    return { head: '', chars: 0, lines: 0, readError: err.code || err.message };
  }

  const text = decodeBuffer(buf);

  const truncated = size > limit;
  const head = text.slice(0, 8000);
  const linesInBuf = (text.match(/\n/g) || []).length;
  const chars = truncated ? Math.round((text.length * size) / Math.max(limit, 1)) : text.length;
  const lines = truncated ? Math.round((linesInBuf * size) / Math.max(limit, 1)) : linesInBuf;

  return { head, chars, lines, truncated, readError: null };
}

/**
 * 识别 AI 来源。
 */
function detectSource(name, head, ext) {
  const evidence = [];
  const scores = new Map();

  const add = (id, w, label) => {
    scores.set(id, (scores.get(id) || 0) + w);
    evidence.push({ id, label, weight: w });
  };

  for (const rule of SOURCE_RULES) {
    for (const p of rule.patterns) {
      if (p.where === 'name') {
        if (p.re.test(name)) add(rule.id, p.w, `文件名命中 ${p.re.source}`);
      } else {
        if (head && p.re.test(head)) add(rule.id, p.w, `内容命中 ${p.re.source}`);
      }
    }
  }

  let aiTraceScore = 0;
  const traceLabels = [];
  for (const p of AI_TRACE_PATTERNS) {
    if (head && p.re.test(head)) {
      aiTraceScore += p.w;
      traceLabels.push(p.label);
    }
  }

  // 强结构特征：两种以上对话角色同现 = 聊天导出结构，比关键词硬得多
  if (head) {
    const roles = new Set();
    const roleRe = /^\s*(human|user|assistant|system|用户|助手)\s*[:：]/gim;
    let m;
    while ((m = roleRe.exec(head)) !== null) roles.add(m[1].toLowerCase());
    if (roles.size >= 2) {
      aiTraceScore += 3;
      traceLabels.push('对话导出结构');
    }
  }

  // 注意：草稿名（untitled/副本/新建）不再计入 AI 痕迹——
  // 人手建的空文件也叫「新建文本文档」，拿它当 AI 证据是 78% 误判的帮凶之一。
  const draftName = DRAFT_NAME_PATTERNS.some((re) => re.test(name));

  let bestId = null;
  let bestScore = 0;
  for (const [id, score] of scores.entries()) {
    if (score > bestScore) {
      bestScore = score;
      bestId = id;
    }
  }

  const rule = bestId ? SOURCE_RULES.find((r) => r.id === bestId) : null;

  // 证据分级（2026-11-06 P1）：文件名提到工具只是弱证据，正文关键词提及同样弱；
  // 两个弱证据（2+2=4）不够定性，必须攒够 5 分（多处信号或正文强特征）才认具体厂商。
  if (rule && bestScore >= 5) {
    return {
      id: rule.id,
      name: rule.name,
      color: rule.color,
      confidence: 'high',
      evidence: evidence.filter((e) => e.id === bestId).slice(0, 3).map((e) => e.label)
    };
  }

  if (rule && bestScore >= 2) {
    return {
      id: 'ai-unknown',
      name: '疑似 AI 生成',
      color: '#9ca3af',
      confidence: 'low',
      evidence: [`提到 ${rule.name}（弱证据，不单独定性）`]
    };
  }

  if (aiTraceScore >= 2) {
    return {
      id: 'ai-unknown',
      name: '疑似 AI 生成',
      color: '#9ca3af',
      confidence: aiTraceScore >= 4 ? 'medium' : 'low',
      evidence: traceLabels.slice(0, 3)
    };
  }

  return { id: 'unknown', name: '未识别', color: '#94a3b8', confidence: 'none', evidence: [], draftName };
}

/**
 * 扫描主入口：收集 → 读样本 → 识别来源 → 基础统计
 */
async function scan(root, options) {
  const startedAt = Date.now();
  const { files: rawFiles, errors, truncated, cancelled } = await collectFiles(root, options || {});

  const files = [];
  const concurrency = 12;
  let cursor = 0;

  async function worker() {
    while (cursor < rawFiles.length) {
      const idx = cursor++;
      const f = rawFiles[idx];
      const sample = await readTextSample(f.path, f.size, 262144);
      const source = detectSource(f.name, sample.head, f.ext);
      files.push({
        id: '',
        path: f.path,
        name: f.name,
        ext: f.ext,
        size: f.size,
        mtime: f.mtime,
        depth: f.depth,
        inProject: !!f.inProject,
        chars: sample.chars,
        lines: sample.lines,
        head: sample.head,
        readError: sample.readError || null,
        source,
        category: null,
        hash: null,
        duplicate: null
      });
    }
  }

  await Promise.all(Array.from({ length: Math.min(concurrency, rawFiles.length || 1) }, () => worker()));

  files.sort((a, b) => b.mtime - a.mtime);
  for (let i = 0; i < files.length; i += 1) files[i].id = `f${i}`;

  const totalSize = files.reduce((s, f) => s + f.size, 0);

  return {
    root: path.resolve(root),
    scannedAt: Date.now(),
    durationMs: Date.now() - startedAt,
    files: files.map((f) => {
      // 不把 head 传给渲染进程之外的地方会造成体积过大，这里保留给分类器用，主进程发 UI 前会裁掉
      return f;
    }),
    errors,
    truncated,
    cancelled: !!cancelled,
    totals: {
      files: files.length,
      size: totalSize,
      errors: errors.length
    }
  };
}

