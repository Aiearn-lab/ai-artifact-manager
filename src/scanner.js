function isTextExt(ext) {
  return TEXT_EXT.has(ext);
}

function isCodeExt(ext) {
  return CODE_EXT.has(ext);
}

function shouldSkipExt(ext) {
  return SKIP_EXT.has(ext);
}

/**
 * 递归收集文件（先只收集路径与基础元数据，不读内容）。
 */
async function collectFiles(root, options) {
  const opts = options || {};
  const maxDepth = Number.isInteger(opts.maxDepth) ? opts.maxDepth : 14;
  const maxFiles = Number.isInteger(opts.maxFiles) ? opts.maxFiles : 50000;
  const whitelist = Array.isArray(opts.whitelist) ? opts.whitelist : [];
  const includeExt = new Set((opts.includeExt || []).map((e) => String(e).toLowerCase()));
  const excludeExt = new Set((opts.excludeExt || []).map((e) => String(e).toLowerCase()));

  const normalizedRoot = path.resolve(root);
  const wlPaths = whitelist
    .filter((w) => w && w.type === 'path' && w.value)
    .map((w) => path.resolve(w.value).toLowerCase());
  const wlExts = new Set(
    whitelist.filter((w) => w && w.type === 'ext' && w.value).map((w) => String(w.value).toLowerCase())
  );

  const files = [];
  const errors = [];
  let truncated = false;

  async function walk(dir, depth) {
    if (files.length >= maxFiles) {
      truncated = true;
      return;
    }
    if (depth > maxDepth) return;

    let entries;
    try {
      entries = await fsp.readdir(dir, { withFileTypes: true });
    } catch (err) {
      errors.push({ path: dir, error: err.code || err.message });
      return;
    }

    for (const entry of entries) {
      if (files.length >= maxFiles) {
        truncated = true;
        return;
      }
      const full = path.join(dir, entry.name);
      const lower = full.toLowerCase();

      if (entry.isSymbolicLink()) continue;

      if (entry.isDirectory()) {
        if (SKIP_DIRS.has(entry.name)) continue;
        if (wlPaths.some((p) => lower === p || lower.startsWith(p + path.sep))) continue;
        await walk(full, depth + 1);
        continue;
      }

      if (!entry.isFile()) continue;

      const ext = path.extname(entry.name).toLowerCase();
      if (shouldSkipExt(ext)) continue;
      if (wlExts.has(ext)) continue;
      if (excludeExt.has(ext)) continue;
      if (includeExt.size > 0 && !includeExt.has(ext)) continue;
      if (!isTextExt(ext)) continue;

      let stat;
      try {
        stat = await fsp.stat(full);
      } catch (err) {
        errors.push({ path: full, error: err.code || err.message });
        continue;
      }

      files.push({
        path: full,
        name: entry.name,
        ext,
        size: stat.size,
        mtime: stat.mtimeMs,
        depth: depth + 1
      });
    }
  }

  await walk(normalizedRoot, 0);
  return { files, errors, truncated };
}

/**
 * 读取文本样本：最多读 maxBytes，返回 head + 字符数估算。
 */
async function readTextSample(filePath, size, maxBytes) {
  const limit = Math.min(size, maxBytes || 262144);
  let buf;
  try {
    const fd = await fsp.open(filePath, 'r');
    try {
      buf = Buffer.alloc(limit);
      const { bytesRead } = await fd.read(buf, 0, limit, 0);
      buf = buf.subarray(0, bytesRead);
    } finally {
      await fd.close();
    }
  } catch (err) {
    return { head: '', chars: 0, lines: 0, readError: err.code || err.message };
  }

  // 去掉 UTF-8 BOM
  let text;
  if (buf.length >= 3 && buf[0] === 0xef && buf[1] === 0xbb && buf[2] === 0xbf) {
    text = buf.subarray(3).toString('utf8');
  } else {
    text = buf.toString('utf8');
  }

  const truncated = size > limit;
  const head = text.slice(0, 8000);
  const linesInBuf = (text.match(/\n/g) || []).length;
  const chars = truncated ? Math.round((text.length * size) / Math.max(limit, 1)) : text.length;
  const lines = truncated ? Math.round((linesInBuf * size) / Math.max(limit, 1)) : linesInBuf;

  return { head, chars, lines, truncated, readError: null };
}

/**
 * 识别 AI 来源。
 */
function detectSource(name, head, ext) {
  const evidence = [];
  const scores = new Map();

  const add = (id, w, label) => {
    scores.set(id, (scores.get(id) || 0) + w);
    evidence.push({ id, label, weight: w });
  };

  for (const rule of SOURCE_RULES) {
    for (const p of rule.patterns) {
      if (p.where === 'name') {
        if (p.re.test(name)) add(rule.id, p.w, `文件名命中 ${p.re.source}`);
      } else {
        if (head && p.re.test(head)) add(rule.id, p.w, `内容命中 ${p.re.source}`);
      }
    }
  }

  let aiTraceScore = 0;
  const traceLabels = [];
  for (const p of AI_TRACE_PATTERNS) {
    if (head && p.re.test(head)) {
      aiTraceScore += p.w;
      traceLabels.push(p.label);
    }
  }

  const draftName = DRAFT_NAME_PATTERNS.some((re) => re.test(name));
  if (draftName) {
    aiTraceScore += 2;
    traceLabels.push('文件名像草稿');
  }

  let bestId = null;
  let bestScore = 0;
  for (const [id, score] of scores.entries()) {
    if (score > bestScore) {
      bestScore = score;
      bestId = id;
    }
  }

  const rule = bestId ? SOURCE_RULES.find((r) => r.id === bestId) : null;

  // 低于阈值的厂商信号不硬认，归为「疑似AI（来源未知）」
  if (rule && bestScore >= 2) {
    return {
      id: rule.id,
      name: rule.name,
      color: rule.color,
      confidence: bestScore >= 4 ? 'high' : 'medium',
      evidence: evidence.filter((e) => e.id === bestId).slice(0, 3).map((e) => e.label)
    };
  }

  if (aiTraceScore >= 2) {
    return {
      id: 'ai-unknown',
      name: '疑似 AI 生成',
      color: '#9ca3af',
      confidence: aiTraceScore >= 4 ? 'medium' : 'low',
      evidence: traceLabels.slice(0, 3)
    };
  }

  return { id: 'unknown', name: '未识别', color: '#94a3b8', confidence: 'none', evidence: [] };
}

/**
 * 扫描主入口：收集 → 读样本 → 识别来源 → 基础统计
 */
async function scan(root, options) {
  const startedAt = Date.now();
  const { files: rawFiles, errors, truncated } = await collectFiles(root, options || {});

  const files = [];
  const concurrency = 12;
  let cursor = 0;

  async function worker() {
    while (cursor < rawFiles.length) {
      const idx = cursor++;
      const f = rawFiles[idx];
      const sample = await readTextSample(f.path, f.size, 262144);
      const source = detectSource(f.name, sample.head, f.ext);
      files.push({
        id: '',
        path: f.path,
        name: f.name,
        ext: f.ext,
        size: f.size,
        mtime: f.mtime,
        depth: f.depth,
        chars: sample.chars,
        lines: sample.lines,
        head: sample.head,
        readError: sample.readError || null,
        source,
        category: null,
        hash: null,
        duplicate: null
      });
    }
  }

  await Promise.all(Array.from({ length: Math.min(concurrency, rawFiles.length || 1) }, () => worker()));

  files.sort((a, b) => b.mtime - a.mtime);
  for (let i = 0; i < files.length; i += 1) files[i].id = `f${i}`;

  const totalSize = files.reduce((s, f) => s + f.size, 0);

  return {
    root: path.resolve(root),
    scannedAt: Date.now(),
    durationMs: Date.now() - startedAt,
    files: files.map((f) => {
      // 不把 head 传给渲染进程之外的地方会造成体积过大，这里保留给分类器用，主进程发 UI 前会裁掉
      return f;
    }),
    errors,
    truncated,
    totals: {
      files: files.length,
      size: totalSize,
      errors: errors.length
    }
  };
}

