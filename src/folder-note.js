'use strict';

/**
 * 卸载保护提醒 —— 往「文件被搬去的地方」放一张说明书。
 * ------------------------------------------------------------------
 * 为什么要有这个模块（v0.8 M4 打包门面）：
 * 卸载只删程序本身，回收箱里的文件、被整理走的文件都还留在磁盘上。
 * 用户在资源管理器里看到两个陌生目录时，不知道里面是什么、能不能删——
 * 要么不敢删（白占地方），要么一把删掉（真丢东西）。
 * 所以把话直接写在文件夹里：卸载之后还在，换台电脑拷过去也还在，
 * 不依赖程序还开着。
 *
 * 规矩：
 * 1. 说明书不存在才写；已经存在就绝不覆盖。用户改过或删掉的，程序不自作主张补回来。
 * 2. 写失败不影响主流程（回收箱/整理目录照常用），静默返回 false。
 * 3. 本模块从头到尾不删任何文件。
 * 4. 文案只讲事实：程序里怎么放回、怎么撤销，都跟现有入口一一对应，不吹做不到的事。
 *
 * 署名：智维工作室 / Zhiwei Studio
 */

const fsp = require('fs').promises;
const path = require('path');

/** 说明书的文件名（带书名号会让人以为是程序垃圾，所以用大白话问句） */
const NOTE_FILE_NAME = '卸载后请看.txt';

/** 回收箱说明：按钮用词与界面逐字对齐（回收箱 / 放回 / 全部放回 / 清空） */
const STASH_NOTE = [
  '这个文件夹是「AI 产出管家」的回收箱。',
  '',
  '里面放的是当时拿不准、先搬走看看的文件。程序没有把它们删掉，',
  '也不会到期自动清理——什么时候清、清哪些，只有你能决定。',
  '',
  '想把某个文件搬回原来的位置：',
  '  1. 打开「AI 产出管家」（卸载了重装回来也一样），',
  '  2. 点首页的「回收箱」，找到它点「放回」；想一次全退回去就点「全部放回」。',
  '  放回时如果原位置已经有同名文件，程序会给它加个序号，绝不覆盖你的东西。',
  '',
  '确认这些文件都不要了：',
  '  · 在回收箱里点「清空（进系统回收站）」，文件会先进 Windows 回收站，还能再反悔一次；',
  '  · 或者直接在资源管理器里删掉这个文件夹（U 盘、网络盘上的删除不进回收站，删前多想一秒）。',
  '',
  '程序卸载后这个文件夹不会被动。你不动它，它就一直在。',
  '',
  '—— 智维工作室 / Zhiwei Studio'
].join('\r\n');

/** 整理目录说明：对应「清理记录 → 撤销」入口 */
const ARCHIVE_NOTE = [
  '这个文件夹是「AI 产出管家」的整理目录。',
  '',
  '你在程序里点「一键整理」后，认为该留下的知识、工具被按分类搬到了下面的子文件夹。',
  '整理是移动，不是复制——所以原位置不会留下一份重复的。',
  '',
  '想把某一批退回原来的位置：',
  '  1. 打开「AI 产出管家」（卸载了重装回来也一样），',
  '  2. 点首页的「清理记录」，找到那一批，点「撤销」。',
  '  退回时如果原位置已经有同名文件，程序会给它加个序号，绝不覆盖你的东西。',
  '',
  '这个文件夹里的东西程序不会自动删除，什么时候清掉由你决定。',
  '卸载程序不会动这里。',
  '',
  '—— 智维工作室 / Zhiwei Studio'
].join('\r\n');

function noteText(kind) {
  return kind === 'archive' ? ARCHIVE_NOTE : STASH_NOTE;
}

/**
 * 确保目录里有一张说明书。
 * @param {string} dir 目标目录（会被递归创建）
 * @param {'stash'|'archive'} kind 说明书种类
 * @returns {Promise<boolean>} true = 这次真的写了一张；false = 已存在或写不进去
 */
async function ensureNote(dir, kind) {
  if (!dir) return false;
  const file = path.join(dir, NOTE_FILE_NAME);
  try {
    await fsp.mkdir(dir, { recursive: true });
    try {
      await fsp.access(file);
      return false; // 已经有了：不覆盖用户改过的，也不重复骚扰
    } catch {
      /* 没有，往下写 */
    }
    await fsp.writeFile(file, noteText(kind), 'utf8');
    return true;
  } catch {
    return false; // 只读目录、磁盘满、路径被占用……都不该拖垮整理这件事
  }
}

module.exports = { ensureNote, noteText, NOTE_FILE_NAME, STASH_NOTE, ARCHIVE_NOTE };
